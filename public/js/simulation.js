/**
 * DEADLOCK LAB: Step-by-Step Banker's Safety Algorithm Visualizer
 * (Directly modeled on educational OS textbook reference diagram)
 */

const SimulationUI = {
    renderSimulationPage() {
        const container = document.getElementById('view-simulation');
        if (!container) return;

        const result = AppState.latestResult;
        const labels = AppState.resourceLabels;
        const n = AppState.n;
        const r = AppState.r;

        if (!result || !result.steps || result.steps.length === 0) {
            container.innerHTML = `
                <div class="card">
                    <div class="card-header">
                        <div class="card-title">
                            <div class="card-title-icon">
                                <svg width="20" height="20" viewBox="0 0 24 24" fill="none" stroke="currentColor"><path d="M5 3l14 9-14 9V3z"/></svg>
                            </div>
                            <div>
                                <h3>Banker's Safety Simulation</h3>
                                <p>Interactive step-by-step trace generated by C engine</p>
                            </div>
                        </div>
                    </div>
                    <div style="text-align: center; padding: 48px 20px;">
                        <svg width="48" height="48" viewBox="0 0 24 24" fill="none" stroke="var(--primary-blue)" style="margin-bottom: 12px; opacity: 0.7;"><circle cx="12" cy="12" r="10"/><polygon points="10 8 16 12 10 16 10 8"/></svg>
                        <h4 style="font-size: 1.1rem; font-weight: 700; margin-bottom: 8px;">No Simulation Trace Loaded</h4>
                        <p style="color: var(--text-secondary); max-width: 480px; margin: 0 auto 20px;">
                            Validate your input matrix on the Dashboard and click <strong>Start Simulation</strong> to generate a complete C-driven execution trace.
                        </p>
                        <button class="btn btn-primary" onclick="App.runBankerSimulation(true)">
                            <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor"><path d="M5 3l14 9-14 9V3z"/></svg>
                            Run Simulation Now
                        </button>
                    </div>
                </div>
            `;
            return;
        }

        const currentStep = result.steps[AppState.currentStepIndex];
        const isSafe = result.isSafe;

        // Top Matrix Overview
        let matrixTablesHtml = `
            <div class="card">
                <div class="card-header">
                    <div class="card-title">
                        <div class="card-title-icon">
                            <svg width="20" height="20" viewBox="0 0 24 24" fill="none" stroke="currentColor"><rect x="3" y="3" width="18" height="18" rx="2"/><path d="M3 9h18"/><path d="M9 21V9"/></svg>
                        </div>
                        <div>
                            <h3>Active System Matrices & State</h3>
                            <p>Current allocation, maximum, need, and unallocated available resources</p>
                        </div>
                    </div>
                    <button class="btn btn-secondary btn-sm" onclick="App.navigateTo('dashboard')">
                        <svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor"><path d="M11 4H4a2 2 0 0 0-2 2v14a2 2 0 0 0 2 2h14a2 2 0 0 0 2-2v-7"/><path d="M18.5 2.5a2.121 2.121 0 0 1 3 3L12 15l-4 1 1-4 9.5-9.5z"/></svg>
                        Edit Inputs
                    </button>
                </div>
                <div class="table-container">
                    <table class="os-table">
                        <thead>
                            <tr>
                                <th rowspan="2">Process</th>
                                <th colspan="${r}">Allocation</th>
                                <th colspan="${r}">Max</th>
                                <th colspan="${r}">Need (Max - Alloc)</th>
                                <th colspan="${r}">Available</th>
                            </tr>
                            <tr>
                                ${labels.map(l => `<th>${l}</th>`).join('')}
                                ${labels.map(l => `<th>${l}</th>`).join('')}
                                ${labels.map(l => `<th>${l}</th>`).join('')}
                                ${labels.map(l => `<th>${l}</th>`).join('')}
                            </tr>
                        </thead>
                        <tbody>
                            ${AppState.alloc.map((row, i) => {
                                const isCurrent = currentStep && currentStep.process === i;
                                const isFinished = currentStep && currentStep.finishAfter[i];
                                let rowClass = '';
                                if (isCurrent) rowClass = 'active-eval-row';
                                else if (isFinished) rowClass = 'row-finished';

                                return `
                                    <tr class="${rowClass}">
                                        <td class="process-label">P${i} ${isCurrent ? '👉' : (isFinished ? '✓' : '')}</td>
                                        ${row.map(v => `<td>${v}</td>`).join('')}
                                        ${AppState.max[i].map(v => `<td>${v}</td>`).join('')}
                                        ${AppState.need[i].map(v => `<td><strong>${v}</strong></td>`).join('')}
                                        ${i === 0 ? `<td rowspan="${n}" style="vertical-align: top; background: white; font-weight: 700; color: var(--primary-blue);" colspan="${r}">
                                            <div style="display: flex; justify-content: space-around; padding: 12px 6px;">
                                                ${AppState.available.map((av, idx) => `<div><span style="font-size:0.75rem; color:var(--text-secondary); display:block;">${labels[idx]}</span>${av}</div>`).join('')}
                                            </div>
                                        </td>` : ''}
                                    </tr>
                                `;
                            }).join('')}
                        </tbody>
                    </table>
                </div>
            </div>
        `;

        // Step by Step Visual Card (Reference Image 3 exact recreation)
        let stepCardHtml = '';
        if (currentStep) {
            const pid = currentStep.process;
            const canFinish = currentStep.canFinish;
            const workBeforeStr = currentStep.workBefore.join(', ');
            const needPidStr = currentStep.need.join(', ');
            const allocPidStr = currentStep.alloc.join(', ');
            const workAfterStr = currentStep.workAfter.join(', ');

            stepCardHtml = `
                <div class="step-simulation-box">
                    <div style="display: flex; align-items: center; justify-content: space-between; margin-bottom: 20px;">
                        <h3 style="font-size: 1.15rem; font-weight: 700; color: var(--text-main); display: flex; align-items: center; gap: 8px;">
                            <span style="background: var(--teal-light); color: var(--teal-accent); padding: 4px 10px; border-radius: var(--radius-sm); font-size: 0.85rem;">
                                Step ${currentStep.stepNumber} of ${result.steps.length}
                            </span>
                            Process Evaluation Trace
                        </h3>
                        <div>
                            ${canFinish 
                                ? `<span style="display: inline-flex; align-items: center; gap: 6px; color: var(--status-safe); font-weight: 700; background: var(--status-safe-bg); padding: 5px 12px; border-radius: 20px; font-size: 0.82rem;">
                                    <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor"><polyline points="20 6 9 17 4 12"/></svg>
                                    Need ≤ Work Satisfied
                                   </span>`
                                : `<span style="display: inline-flex; align-items: center; gap: 6px; color: var(--status-waiting); font-weight: 700; background: var(--status-waiting-bg); padding: 5px 12px; border-radius: 20px; font-size: 0.82rem;">
                                    <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor"><circle cx="12" cy="12" r="10"/><line x1="12" y1="8" x2="12" y2="12"/><line x1="12" y1="16" x2="12.01" y2="16"/></svg>
                                    Need > Work (P${pid} Must Wait)
                                   </span>`
                            }
                        </div>
                    </div>

                    <!-- Step Evaluation Box (Matches reference Step 2) -->
                    <div class="step-card ${canFinish ? '' : 'circle-highlight'}">
                        <div class="step-badge-title">
                            <span>Step Evaluation: Process P<sub>${pid}</sub></span>
                            ${canFinish 
                                ? `<span style="color: var(--status-safe); font-size: 1.4rem;">✔</span>` 
                                : `<span style="color: var(--status-waiting); font-size: 1.4rem;">⏳</span>`}
                        </div>
                        
                        <div style="font-size: 1.05rem; margin-bottom: 8px;">
                            <u>For i = ${pid}</u>
                        </div>
                        <div style="font-size: 1rem; color: var(--text-secondary); margin-bottom: 10px;">
                            Need<sub>${pid}</sub> = ${needPidStr}
                        </div>
                        <div style="font-size: 1.05rem; margin-bottom: 12px;">
                            Finish [${pid}] is <strong>false</strong> and 
                            <span style="display: inline-block; padding: 2px 8px; border-radius: 12px; background: ${canFinish ? '#DCFCE7' : '#FEF3C7'}; font-weight: 700;">
                                Need<sub>${pid}</sub> (${needPidStr}) ≤ Work (${workBeforeStr})
                            </span>
                        </div>
                        <div style="font-weight: 600; color: ${canFinish ? 'var(--status-safe)' : 'var(--status-waiting)'};">
                            ${canFinish ? `So P<sub>${pid}</sub> can finish and joins the safe sequence.` : `P<sub>${pid}</sub> cannot be satisfied with current Work vector. Must wait.`}
                        </div>
                    </div>

                    <!-- Step Update Box (Matches reference Step 3) -->
                    ${canFinish ? `
                        <div class="step-card active-step">
                            <div class="step-badge-title">
                                <span>Resource Reclamation & Work Update</span>
                            </div>
                            <div class="step-formula-line">
                                <span style="font-size: 0.85rem; color: var(--text-secondary); display: block; margin-bottom: 2px;">
                                    (${workBeforeStr}) &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; (${allocPidStr})
                                </span>
                                <strong>Work = Work + Allocation<sub>${pid}</sub></strong>
                            </div>

                            <div class="step-vectors-row">
                                <div class="vector-display">
                                    <span class="vector-label">Work =</span>
                                    <div class="vector-cells circle-highlight">
                                        ${currentStep.workAfter.map((val, j) => `
                                            <div class="vector-cell">
                                                <span class="cell-header">${labels[j]}</span>
                                                ${val}
                                            </div>
                                        `).join('')}
                                    </div>
                                </div>

                                <div class="vector-display">
                                    <span class="vector-label">Finish =</span>
                                    <div class="vector-cells">
                                        ${currentStep.finishAfter.map((f, p) => `
                                            <div class="vector-cell finish-cell ${f ? 'true-flag' : 'false-flag'} ${p === pid ? 'circle-highlight' : ''}">
                                                <span class="cell-header">${p}</span>
                                                ${f ? 'true' : 'false'}
                                            </div>
                                        `).join('')}
                                    </div>
                                </div>
                            </div>
                        </div>
                    ` : ''}

                    <!-- Step Controls Bar -->
                    <div class="step-controls-bar">
                        <button class="btn btn-secondary btn-sm" onclick="SimulationUI.firstStep()" ${AppState.currentStepIndex === 0 ? 'disabled' : ''}>
                            <svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor"><polygon points="19 20 9 12 19 4 19 20"/><line x1="5" y1="19" x2="5" y2="5"/></svg>
                            First
                        </button>
                        <button class="btn btn-secondary" onclick="SimulationUI.prevStep()" ${AppState.currentStepIndex === 0 ? 'disabled' : ''}>
                            <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor"><polyline points="15 18 9 12 15 6"/></svg>
                            Previous
                        </button>
                        <button class="btn btn-primary" onclick="SimulationUI.togglePlay()">
                            ${AppState.isPlaying 
                                ? `<svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor"><rect x="6" y="4" width="4" height="16"/><rect x="14" y="4" width="4" height="16"/></svg> Pause`
                                : `<svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor"><polygon points="5 3 19 12 5 21 5 3"/></svg> Auto Play`}
                        </button>
                        <button class="btn btn-secondary" onclick="SimulationUI.nextStep()" ${AppState.currentStepIndex >= result.steps.length - 1 ? 'disabled' : ''}>
                            Next
                            <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor"><polyline points="9 18 15 12 9 6"/></svg>
                        </button>
                        <button class="btn btn-secondary btn-sm" onclick="SimulationUI.lastStep()" ${AppState.currentStepIndex >= result.steps.length - 1 ? 'disabled' : ''}>
                            Last
                            <svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor"><polygon points="5 4 15 12 5 20 5 4"/><line x1="19" y1="5" x2="19" y2="19"/></svg>
                        </button>
                        <span class="step-counter-text">
                            ${AppState.currentStepIndex + 1} / ${result.steps.length}
                        </span>
                    </div>
                </div>
            `;
        }

        // Completion Banner
        const isComplete = AppState.currentStepIndex === result.steps.length - 1;
        let finalBannerHtml = '';
        if (isComplete) {
            if (isSafe) {
                finalBannerHtml = `
                    <div class="status-banner safe">
                        <svg width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor"><path d="M22 11.08V12a10 10 0 1 1-5.93-9.14"/><polyline points="22 4 12 14.01 9 11.01"/></svg>
                        <div>
                            <h4 style="font-weight: 700; font-size: 1.05rem; margin-bottom: 4px;">System is SAFE</h4>
                            <p style="font-size: 0.9rem; margin-bottom: 8px;">${result.explanation}</p>
                            <div class="safe-sequence-strip">
                                <span style="font-weight: 700; font-size: 0.85rem; color: #166534;">Safe Sequence:</span>
                                ${result.safeSequence.map((pid, idx) => `
                                    <span class="seq-node">P${pid}</span>
                                    ${idx < result.safeSequence.length - 1 ? '<span class="seq-arrow">→</span>' : ''}
                                `).join('')}
                            </div>
                        </div>
                    </div>
                `;
            } else {
                finalBannerHtml = `
                    <div class="status-banner unsafe">
                        <svg width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor"><polygon points="7.86 2 16.14 2 22 7.86 22 16.14 16.14 22 7.86 22 2 16.14 2 7.86 7.86 2"/><line x1="12" y1="8" x2="12" y2="12"/><line x1="12" y1="16" x2="12.01" y2="16"/></svg>
                        <div>
                            <h4 style="font-weight: 700; font-size: 1.05rem; margin-bottom: 4px;">System is in an UNSAFE State</h4>
                            <p style="font-size: 0.9rem;">${result.explanation}</p>
                        </div>
                    </div>
                `;
            }
        }

        container.innerHTML = matrixTablesHtml + stepCardHtml + finalBannerHtml;
    },

    nextStep() {
        if (!AppState.latestResult || !AppState.latestResult.steps) return;
        if (AppState.currentStepIndex < AppState.latestResult.steps.length - 1) {
            AppState.currentStepIndex++;
            this.renderSimulationPage();
        } else {
            this.pause();
        }
    },

    prevStep() {
        if (AppState.currentStepIndex > 0) {
            AppState.currentStepIndex--;
            this.renderSimulationPage();
        }
    },

    firstStep() {
        AppState.currentStepIndex = 0;
        this.renderSimulationPage();
    },

    lastStep() {
        if (AppState.latestResult && AppState.latestResult.steps) {
            AppState.currentStepIndex = AppState.latestResult.steps.length - 1;
            this.renderSimulationPage();
        }
    },

    togglePlay() {
        if (AppState.isPlaying) {
            this.pause();
        } else {
            this.play();
        }
    },

    play() {
        AppState.isPlaying = true;
        if (AppState.currentStepIndex >= AppState.latestResult.steps.length - 1) {
            AppState.currentStepIndex = 0;
        }
        this.renderSimulationPage();
        AppState.playInterval = setInterval(() => {
            if (AppState.currentStepIndex < AppState.latestResult.steps.length - 1) {
                AppState.currentStepIndex++;
                this.renderSimulationPage();
            } else {
                this.pause();
            }
        }, 1500);
    },

    pause() {
        AppState.isPlaying = false;
        if (AppState.playInterval) {
            clearInterval(AppState.playInterval);
            AppState.playInterval = null;
        }
        this.renderSimulationPage();
    }
};

window.SimulationUI = SimulationUI;
